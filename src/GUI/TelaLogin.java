    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
    
    // aqui será consultado o login e senha inseridos e verá se há algum correspondente na lista de usuários, para ceder as permissões ou negar o acesso 
        
    Usuario usuario1 = new Usuario();
    UsuarioConexao uc = new UsuarioConexao();
        String strLogin = txtUsuario.getText();
        String strSenha = txtSenha.getText();
        usuario1.setLogin(strLogin);
        usuario1.setSenha(strSenha);

        usuario1 = uc.verificar(usuario1); /**verificando se existe o login e senha digitados existem*/
        if (usuario1 != null){
          
            String login = usuario1.getLogin();
            
             /**avaliando qual usuario foi acessado ou se não existe*/
            if (login.equalsIgnoreCase("gerente")){
                JOptionPane.showMessageDialog(null, "Bem-vindo, gerente ");
                TelaLista tela = new TelaLista();
                tela.setVisible(true);
                tela.desabilitarDespesas();
                dispose();
            } else if (login.equalsIgnoreCase("financeiro")){
                JOptionPane.showMessageDialog(null, "Bem-vindo, financeiro ");
                TelaLista tela = new TelaLista();
                tela.setVisible(true);                
                tela.desabilitarPedidosEntregadores();
                dispose();
            } else if(login.equalsIgnoreCase("fiscal")){
                JOptionPane.showMessageDialog(null, "Bem-vindo, fiscal ");
                TelaLista tela = new TelaLista();
                tela.setVisible(true);         
                tela.desabilitarCadastro();
                tela.desabilitarDespesas();
                tela.desabilitarExclusão();
                dispose();
            }else {
            JOptionPane.showMessageDialog(null, "erro de identificação, o Login ou senha digitados estão incorretos.");
        }
       
        }
    }//GEN-LAST:event_btnEntrarActionPerformed

