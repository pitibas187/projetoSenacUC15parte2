    private void atualizarTabelaD(List a) {

        if (!a.isEmpty()) {

            Despesas d;

            tableModel = new DefaultTableModel(tableColumns, 0);
            /**
             * pegando os dados da lista
             */
            for (int i = 0; i < a.size(); i++) {

                d = (Despesas) a.get(i);

                String valor = String.valueOf(d.getValor());
                String id = String.valueOf(d.getId());

                String[] rowData = {id, d.getCategoria(), valor, d.getDetalhes()};

                tableModel.addRow(rowData);
                /**
                 * preenchendo o molde da tabela
                 */
            }

            tblLista.setModel(tableModel);
            /**
             * preechendo a tabela
             */
        } else {

            tableModel = new DefaultTableModel(tableColumns, 0);
            tblLista.setModel(tableModel);
        }
    }

