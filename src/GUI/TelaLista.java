    private void atualizarTabelaP(List a) {

        if (!a.isEmpty()) {

            Pedidos p;

            tableModel3 = new DefaultTableModel(tableColumns3, 0);
            /**
             * pegando os dados da lista
             */
            for (int i = 0; i < a.size(); i++) {

                p = (Pedidos) a.get(i);

                String peso = String.valueOf(p.getPeso());
                String id = String.valueOf(p.getId());
                String idEntregador = String.valueOf(p.getIdEntregador());

                String[] rowData = {id, p.getCliente(), p.getCidade(), idEntregador, peso};

                tableModel3.addRow(rowData);
                /**
                 * preenchendo o molde da tabela
                 */
            }

            tblLista.setModel(tableModel3) /**
                     * preechendo a tabela
                     */
                    ;
        } else {

            tableModel3 = new DefaultTableModel(tableColumns3, 0);
            tblLista.setModel(tableModel3);
        }
    }

