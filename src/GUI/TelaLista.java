    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        String strId = txtPesquisar.getText();
        String comando;
        int id1 = Integer.parseInt(strId);
        switch (tabela) {
            case 1:
                dc.DeletarDespesa(id1);
                atualizarTabelaD(dc.pesquisarTudo());
                break;
            case 2:
                ec.deletarEntregador(id1);
                atualizarTabelaE(ec.pesquisarTudo());
                break;
            case 3:
                comando = "delete from pedidos where id=? ";
                pc.deletarPedidos(id1);
                atualizarTabelaP(pc.pesquisarTudo());
                break;
            default:
                break;
        }


    }//GEN-LAST:event_btnExcluirActionPerformed

